"""Generate firmware/pico2/field_tables.py — the board's static map (barrier polygons and the marking
band) plus the estimator constants, extracted from the software field so the on-board filter needs no
field JSON or stockcar import.

Usage: uv run --no-project --python 3.12 python -B -I tools/build_field_tables.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "software"))
from stockcar.field import Field  # noqa: E402
from stockcar.sensors import COUNTS_PER_REV, REFLECTANCE_OFFSETS, TOF_MAX_IN, TOF_SENSORS, WHEEL_RADIUS_IN, Band  # noqa: E402
from stockcar.estimator import GYRO_NOISE_RAD_S, LINE_NOISE_IN, SHALLOWEST_CROSSING  # noqa: E402


def _rings(points):
    return [[round(p[0], 4), round(p[1], 4)] for p in points]


def render_tables():
    field = Field()
    band = Band(field)
    lines = [
        "# Generated by tools/build_field_tables.py — do not edit by hand.",
        "# Static map and constants for the on-board EKF, extracted from the organizer CAD field.",
        "# Coordinates are inches in the field-v10 frame; the band is the white octagonal marking band.",
        "",
        "COUNTS_PER_REV = %d" % COUNTS_PER_REV,
        "WHEEL_RADIUS_IN = %r" % WHEEL_RADIUS_IN,
        "TOF_MAX_IN = %r" % TOF_MAX_IN,
        "GYRO_NOISE_RAD_S = %r" % GYRO_NOISE_RAD_S,
        "LINE_NOISE_IN = %r" % LINE_NOISE_IN,
        "SHALLOWEST_CROSSING = %r" % SHALLOWEST_CROSSING,
        "REFLECTANCE_OFFSETS = %r" % [list(o) for o in REFLECTANCE_OFFSETS],
        "TOF_SENSORS = %r" % [list(s) for s in TOF_SENSORS],
        "",
        "BARRIERS = %r" % [_rings(p) for p in field.barriers()],
        "BAND_OUTER = %r" % _rings(band.outer),
        "BAND_INNER = %r" % _rings(band.inner),
        "",
    ]
    return "\n".join(lines)


def main():
    out = ROOT / "firmware" / "pico2" / "field_tables.py"
    out.write_text(render_tables() + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()